/** Ограничитель частоты нажатий с панели openHASP. Без I/O. */

// Одно нажатие в секунду на каждый топик. Секунда взята не с потолка: строка на
// панели — это физическая кнопка на плате, и палец, снятый с неё неровно, даёт
// две-три посылки подряд. Плюс тот же порядок, что у тика демона claude-wt,
// после которого раскладка успевает обновиться.
const DEFAULT_INTERVAL_MS = 1000;

/**
 * Обёртка, пропускающая не чаще одного вызова в интервал.
 *
 * Первое нажатие проходит немедленно, всё, что прилетело следом внутри окна,
 * отбрасывается совсем — не откладывается на потом.
 *
 * Отбрасывать, а не откладывать: отложенное нажатие сделает ровно то же, что
 * уже сделано секунду назад, — переведёт фокус туда же или восстановит тот же
 * снимок. Отложенное же нажатие по *другой* строке проиграет ещё интереснее:
 * фокус уедет через секунду после того, как человек уже смотрит в первое окно.
 *
 * Передний фронт, а не задний: панель должна отзываться на касание сразу.
 * Плата за это — промах при быстром исправлении («не туда ткнул, тыкаю в
 * соседнюю»): выиграет первое нажатие, и повторить придётся через секунду.
 * Размен сознательный, промахи там редки, а задержка на каждом нажатии
 * ощущалась бы всегда.
 *
 * Окно своё у каждой обёртки, поэтому строки сессий и кнопка восстановления
 * друг друга не глушат: это разные действия, и общий счётчик означал бы, что
 * нажатие на строку съедает нажатие на кнопку.
 *
 * `now` и `onDrop` — швы для проверки и для журнала: молча проглоченное
 * нажатие выглядит как поломка, поэтому вызывающий его логирует.
 */
function throttlePress(handler, {intervalMs = DEFAULT_INTERVAL_MS, now = Date.now, onDrop} = {}) {
  // -Infinity, а не 0: с нулём первое нажатие в первую же секунду после
  // старта процесса (Date.now() тут ни при чём, счёт идёт от эпохи) прошло бы,
  // но с подставными часами в тестах — нет.
  let lastAt = -Infinity;
  return (...args) => {
    const at = now();
    if (at - lastAt < intervalMs) {
      onDrop?.(...args);
      return undefined;
    }
    lastAt = at;
    return handler(...args);
  };
}

module.exports = {DEFAULT_INTERVAL_MS, throttlePress};
